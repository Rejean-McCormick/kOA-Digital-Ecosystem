#!/usr/bin/env python3
"""Render final-system Markdown as flat GitHub Wiki pages.

The central repository remains the canonical documentation source. This tool
writes/checks only mirror pages bearing a generated header; it never changes
existing, hand-authored wiki pages (Home, Status, _Sidebar, etc.).
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
REPO_URL = "https://github.com/Rejean-McCormick/kOA-Digital-Ecosystem"
LINK_RE = re.compile(r"(?<!!)\[([^\]\n]+)\]\(([^)]+)\)")
GENERATED_MARKER = "<!-- Generated by scripts/render_target_wiki.py; edit the canonical repository source instead. -->"


def page_name(relative: Path) -> str:
    """Stable, globally unique wiki slug for a canonical Markdown file."""
    s = relative.as_posix()
    explicit = {
        "docs/target/README.md": "Final-System",
        "docs/target/architecture.md": "Final-Architecture",
        "docs/target/journeys.md": "Final-Journeys",
        "docs/target/PORTFOLIO.md": "Final-Portfolio",
        "docs/target/BOUNDARIES.md": "Final-Boundaries",
        "docs/target/CODE_ALIGNMENT_INSTRUCTIONS.md": "Final-Code-Alignment",
        "docs/target/SNAPSHOT_RECONCILIATION.md": "Final-Snapshot-Reconciliation",
        "docs/target/adjacent-projects.md": "Final-Adjacent-Projects",
        "docs/target/functional-chains/README.md": "Functional-Chains",
        "docs/status/current.md": "Implementation-Status",
        "docs/inventory/README.md": "Repository-Inventory",
    }
    if s in explicit:
        return explicit[s]
    base = Path(s).stem
    if s.startswith("docs/target/functional-chains/chains/"):
        return base
    if s.startswith("docs/target/functional-chains/"):
        return "Functional-" + base
    raise ValueError(f"Not a wiki mirror source: {s}")


def build_map(root: Path = ROOT) -> dict[Path, str]:
    files = sorted((root / "docs/target").rglob("*.md")) + [
        root / "docs/status/current.md", root / "docs/inventory/README.md"
    ]
    mapping = {f.resolve(): page_name(f.relative_to(root)) for f in files}
    names = list(mapping.values())
    if len(set(n.lower() for n in names)) != len(names):
        raise ValueError("Duplicate case-insensitive wiki page slugs")
    return mapping


def repo_source_url(rel: Path, ref: str) -> str:
    # Ref is selectable: the archive cannot establish the default remote branch.
    return f"{REPO_URL}/blob/{quote(ref, safe='/')}/{quote(rel.as_posix(), safe='/')}"


def rewrite_links(text: str, source: Path, mapping: dict[Path, str], root: Path, ref: str) -> str:
    def replace(match: re.Match[str]) -> str:
        label, dest = match.groups()
        # Absolute URLs and intra-page fragment anchors already work in a wiki.
        if dest.startswith(("https://", "http://", "mailto:", "#", "data:")):
            return match.group(0)
        # Existing sources use simple local destinations (no Markdown link titles).
        plain, sep, fragment = dest.partition("#")
        if not plain:
            return match.group(0)
        link_target = (source.parent / plain).resolve()
        if not link_target.is_relative_to(root.resolve()):
            raise ValueError(f"Link escapes repo: {source}: {dest}")
        if not link_target.exists():
            raise ValueError(f"Broken canonical link in {source}: {dest}")
        if link_target in mapping:
            new_target = mapping[link_target]
        else:
            new_target = repo_source_url(link_target.relative_to(root), ref)
        if sep:
            new_target += "#" + fragment
        return f"[{label}]({new_target})"

    return LINK_RE.sub(replace, text)


def render(root: Path = ROOT, ref: str = "main") -> dict[str, str]:
    mapping = build_map(root)
    out = {}
    for source, slug in mapping.items():
        original = source.read_text(encoding="utf-8")
        digest = hashlib.sha256(original.encode("utf-8")).hexdigest()
        relative = source.relative_to(root)
        header = (f"{GENERATED_MARKER}\n\n"
                  f"> **Final-system documentation mirror.** Canonical file: "
                  f"[`{relative.as_posix()}`]({repo_source_url(relative, ref)}). "
                  f"SHA-256: `{digest}`. "
                  "Target requirements are not evidence of deployed behavior.\n\n")
        converted = rewrite_links(original, source, mapping, root, ref)
        out[slug + ".md"] = header + converted.rstrip() + "\n"
    return out


def validate_pages(pages: dict[str, str]) -> list[str]:
    errors = []
    set_names = set(pages)
    for name, body in pages.items():
        if not body.startswith(GENERATED_MARKER):
            errors.append(f"{name}: missing generation warning")
        for _, target in LINK_RE.findall(body):
            if target.startswith(("https://", "http://", "mailto:", "#", "data:")):
                continue
            slug = target.split("#", 1)[0]
            if slug + ".md" not in set_names:
                errors.append(f"{name}: unresolved wiki link: {target}")
    return errors


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output-dir", type=Path, help="Extracted GitHub wiki checkout (required for --write/--check)")
    p.add_argument("--source-ref", default="main", help="Ref for clickable GitHub canonical source links")
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Write/update generated wiki mirror pages")
    mode.add_argument("--check", action="store_true", help="Compare output directory with expected generated pages")
    mode.add_argument("--validate", action="store_true", help="Validate source links and generated wiki links without writing")
    args = p.parse_args()
    try:
        pages = render(ref=args.source_ref)
        errors = validate_pages(pages)
        if (args.write or args.check) and args.output_dir is None:
            p.error("--output-dir is required with --write and --check")
        if args.output_dir and args.check:
            for name, expected in pages.items():
                f = args.output_dir / name
                if not f.exists():
                    errors.append(f"Missing wiki mirror page: {name}")
                elif f.read_text(encoding="utf-8") != expected:
                    errors.append(f"Stale wiki mirror page: {name}")
            for f in args.output_dir.glob("*.md"):
                if f.name not in pages and f.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
                    errors.append(f"Unreferenced generated wiki page: {f.name}")
        if errors:
            print("\n".join("FAIL: " + e for e in errors))
            return 1
        if args.write:
            args.output_dir.mkdir(parents=True, exist_ok=True)
            for name, content in pages.items():
                (args.output_dir / name).write_text(content, encoding="utf-8")
        print(f"PASS: {len(pages)} deterministic wiki pages; no unresolved canonical or wiki links")
        return 0
    except (OSError, ValueError) as exc:
        print(f"FAIL: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
